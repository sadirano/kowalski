const LANG_ORDER   = ['pt', 'en', 'ja'];
const LANG_LOCALES = { pt: 'pt-BR', en: 'en-US', ja: 'ja-JP' };
const LANG_NAMES   = { pt: 'Português (Brasil)', en: 'English (US)', ja: '日本語' };
let _lang = 'en';
function setLangFrom(settings) {
  _lang = Object.hasOwn(I18N, settings.ui_lang) ? settings.ui_lang : 'en';
}

function t(key, vars) {
  let s = (I18N[_lang] && I18N[_lang][key]) ?? I18N.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
  return s;
}
function locale() { return LANG_LOCALES[_lang]; }

function cycleLang() {
  const before = _lang;
  _lang = LANG_ORDER[(LANG_ORDER.indexOf(_lang) + 1) % LANG_ORDER.length];
  // A failed save goes back to the language the daemon still has.
  setPref('ui_lang', _lang).catch(e => { showError(e.message); _lang = before; relabel(); });
  relabel();
}

// A provider's field or prompt label in the current language, when the
// provider gives one (`labels`), else its plain label.
function providerLabel(x) { return (x.labels && x.labels[_lang]) || x.label; }
function providerHint(x) { return (x.hints && x.hints[_lang]) || x.hint || ''; }

function relabel() {
  applyLang();
  // Re-render everything that bakes labels into its markup.
  loadCurrent(); renderSidebar(); renderSchedule(); loadDay(selectedDate, { chart: true }); renderChartGroups();
  if (isSearchOpen()) renderSearch();
  relabelTour();
}

// applyLang fills every data-i18n* annotated element.
function applyLang() {
  document.documentElement.lang = locale();
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}

